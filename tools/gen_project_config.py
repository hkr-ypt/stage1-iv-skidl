#!/usr/bin/env python3
"""
gen_project_config.py — generate the project's KiCad configuration and its
library dependency record.
==========================================================================

Emits three files, all derived from the live circuit so none of them can drift
from what the design actually uses:

    sym-lib-table                 project symbol library table
    fp-lib-table                  project footprint library table
    docs/LIBRARY_DEPENDENCIES.md  every external lib_id, pinned to a revision

**No absolute path is ever written.** Symbol and footprint libraries are
referenced through ``${KIPRJMOD}`` (the project directory, which KiCad defines)
and ``${KICAD9_SYMBOL_DIR}`` / ``${KICAD9_FOOTPRINT_DIR}`` (which KiCad
predefines to its own install and which a user may override). Anyone cloning
the repository gets working tables without editing anything.

Usage::

    python3 tools/gen_project_config.py           # write the three files
    python3 tools/gen_project_config.py --check   # verify they are current
"""

from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, REPO_ROOT)

from resolve_kicad_libs import KicadLibraries, LibraryNotFound  # noqa: E402

SYM_LIB_TABLE = os.path.join(REPO_ROOT, "sym-lib-table")
FP_LIB_TABLE = os.path.join(REPO_ROOT, "fp-lib-table")
DEPS_DOC = os.path.join(REPO_ROOT, "docs", "LIBRARY_DEPENDENCIES.md")

PROJECT_LIB_NICK = "stage1_iv"

# KiCad predefines these; a user may override them. Never an absolute path.
SYMBOL_DIR_VAR = "${KICAD9_SYMBOL_DIR}"
FOOTPRINT_DIR_VAR = "${KICAD9_FOOTPRINT_DIR}"


def gather():
    """Collect every identifier the design uses, from the live circuit."""
    import main as project_main
    _n, _parts, circuit = project_main.build()

    upstream_symbols = {}     # lib_id -> [refs]
    project_symbols = {}      # lib_id -> [refs]
    footprints = {}           # fp_id  -> [refs]
    for part in sorted(circuit.parts, key=lambda p: p.ref):
        lib_id = (part.fields.get("KiCad_Lib") or "").strip()
        proj = (part.fields.get("Project_Symbol") or "").strip()
        if lib_id:
            target = (project_symbols if lib_id.startswith(PROJECT_LIB_NICK + ":")
                      else upstream_symbols)
            target.setdefault(lib_id, []).append(part.ref)
        if proj:
            project_symbols.setdefault(proj, []).append(part.ref)
        fp = (part.footprint or "").strip()
        if fp:
            footprints.setdefault(fp, []).append(part.ref)
    return circuit, upstream_symbols, project_symbols, footprints


def sym_lib_table(upstream_symbols):
    """Project symbol library table. Paths via ${KIPRJMOD} / ${KICAD9_SYMBOL_DIR}."""
    rows = [
        f'  (lib (name "{PROJECT_LIB_NICK}")(type "KiCad")'
        f'(uri "${{KIPRJMOD}}/libraries/{PROJECT_LIB_NICK}.kicad_sym")(options "")'
        f'(descr "Stage 1 I-V project symbols. EVERY symbol the schematic '
        f'instantiates lives here; generated by tools/author_project_symbols.py'
        f' so the schematic cache and this library cannot disagree."))'
    ]
    for nick in sorted({lid.split(":", 1)[0] for lid in upstream_symbols}):
        rows.append(
            f'  (lib (name "{nick}")(type "KiCad")'
            f'(uri "{SYMBOL_DIR_VAR}/{nick}.kicad_sym")(options "")'
            f'(descr "Upstream KiCad library this design resolves pin numbers '
            f'against. Not referenced by any schematic symbol - see '
            f'docs/LIBRARY_DEPENDENCIES.md."))')
    return "(sym_lib_table\n  (version 7)\n" + "\n".join(rows) + "\n)\n"


def fp_lib_table(footprints):
    """Project footprint library table. Paths via ${KICAD9_FOOTPRINT_DIR}."""
    rows = []
    for nick in sorted({fp.split(":", 1)[0] for fp in footprints}):
        rows.append(
            f'  (lib (name "{nick}")(type "KiCad")'
            f'(uri "{FOOTPRINT_DIR_VAR}/{nick}.pretty")(options "")'
            f'(descr "Upstream KiCad footprint library used by this design."))')
    return "(fp_lib_table\n  (version 7)\n" + "\n".join(rows) + "\n)\n"


def deps_doc(upstream_symbols, project_symbols, footprints, provenance, libs):
    """docs/LIBRARY_DEPENDENCIES.md — generated, never hand-written."""
    # Deliberately NO generation timestamp and NO machine paths: this file is
    # regenerated in CI and compared byte-for-byte against the committed copy,
    # so anything that varies by day or by machine makes --check unsatisfiable.
    # The pinned tag and commit below are the meaningful "when".
    sym = {k: v for k, v in provenance.get("symbols", {}).items() if k != "path"}
    fpv = {k: v for k, v in provenance.get("footprints", {}).items() if k != "path"}

    out = []
    A = out.append
    A("# Library dependencies")
    A("")
    A("**GENERATED FILE — do not edit by hand.**")
    A("Regenerate with `python3 tools/gen_project_config.py`; verify with")
    A("`python3 tools/gen_project_config.py --check`. It is built from the live")
    A("circuit, so it cannot describe anything the design does not actually use.")
    A("")
    A("Resolved against:")
    A("")
    A("| | repository | pinned revision | commit |")
    A("|---|---|---|---|")
    for label, info in (("symbols", sym), ("footprints", fpv)):
        A(f"| {label} | `{info.get('repository', 'n/a')}` | "
          f"`{info.get('tag', 'UNPINNED')}` | `{info.get('commit', 'n/a')}` |")
    A("")
    A("Install exactly this revision with `tools/install_kicad_libs.sh`. The")
    A("build does not require it — see \"Building without KiCad\" below — but")
    A("every pin number below was read from it.")
    A("")

    A("## Symbols the schematic instantiates")
    A("")
    A("Every schematic symbol resolves to the **project** library, so KiCad")
    A("never has to find an upstream symbol to open or ERC this design.")
    A("")
    A("| lib_id | symbols | resolves via |")
    A("|---|---|---|")
    A(f"| `{PROJECT_LIB_NICK}:*` | {len(project_symbols)} | "
      f"`${{KIPRJMOD}}/libraries/{PROJECT_LIB_NICK}.kicad_sym` (committed) |")
    A("")

    A("## Upstream symbols the pin numbers were read from")
    A("")
    A("These are the authoritative sources for pin numbering. They are recorded")
    A("as each part's `KiCad_Lib` field and verified by")
    A("`validation/footprint_check.py` whenever the libraries are installed.")
    A("")
    A("| upstream lib_id | used by | symbol read from |")
    A("|---|---|---|")
    for lib_id in sorted(upstream_symbols):
        refs = upstream_symbols[lib_id]
        src = "—"
        if libs is not None:
            s = libs.get_symbol(lib_id)
            if s is not None:
                src = f"`{os.path.basename(s.file)}:{s.line}`"
        shown = ", ".join(refs[:6]) + (f" +{len(refs) - 6}" if len(refs) > 6 else "")
        A(f"| `{lib_id}` | {shown} | {src} |")
    A("")

    A("## Footprints")
    A("")
    A("Footprints are **not** vendored: they resolve through")
    A(f"`{FOOTPRINT_DIR_VAR}` via the committed `fp-lib-table`. This is a real")
    A("runtime dependency — laying out the PCB needs these libraries installed.")
    A("")
    A("| footprint | used by |")
    A("|---|---|")
    for fp_id in sorted(footprints):
        refs = footprints[fp_id]
        shown = ", ".join(refs[:6]) + (f" +{len(refs) - 6}" if len(refs) > 6 else "")
        A(f"| `{fp_id}` | {shown} |")
    A("")

    A("## Building without KiCad")
    A("")
    A("`python3 main.py` runs with no KiCad installed. `libraries/custom_symbols.py`")
    A("falls back to the committed project library for pin data, and the build")
    A("banner reports **SKIPPED** for every KiCad-conformance check rather than")
    A("anything resembling a pass. Run `python3 tools/kicad_env.py --diagnose`")
    A("to see what resolved and whether the installation is complete.")
    A("")
    return "\n".join(out)


def build_all():
    circuit, upstream_symbols, project_symbols, footprints = gather()
    try:
        libs = KicadLibraries()
        provenance = libs.provenance()
    except LibraryNotFound:
        libs, provenance = None, {}
    return {
        SYM_LIB_TABLE: sym_lib_table(upstream_symbols),
        FP_LIB_TABLE: fp_lib_table(footprints),
        DEPS_DOC: deps_doc(upstream_symbols, project_symbols, footprints,
                           provenance, libs),
    }, libs


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--check", action="store_true",
                    help="verify the committed files are current")
    args = ap.parse_args(argv)

    files, libs = build_all()
    if libs is None:
        print("KiCad libraries not found — the dependency record cannot be "
              "regenerated without them. Run tools/kicad_env.py --diagnose.",
              file=sys.stderr)
        return 2

    if args.check:
        problems = [p for p, text in files.items()
                    if not os.path.isfile(p)
                    or open(p, encoding="utf-8").read() != text]
        if problems:
            for p in problems:
                print(f"FAIL stale or missing (regenerate): "
                      f"{os.path.relpath(p, REPO_ROOT)}", file=sys.stderr)
            return 1
        print("OK  sym-lib-table, fp-lib-table and docs/LIBRARY_DEPENDENCIES.md "
              "are current")
        return 0

    for path, text in files.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"wrote {os.path.relpath(path, REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
